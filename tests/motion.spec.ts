import { test, expect } from '@playwright/test'

test.use({ channel: 'chrome', viewport: { width: 1280, height: 720 }, reducedMotion: 'no-preference' })
const base = process.env.HEYDAY_WEB_TEST_URL ?? 'http://127.0.0.1:3000'

test('wheel scrolling moves the hero and reveals content once without changing layout', async ({ page }) => {
  await page.goto(base)
  await expect(page.getByRole('switch')).toBeEnabled()
  const hero = page.locator('.hero-copy')
  const title = page.getByRole('heading', { name: 'Your finances. Your choice.' })
  const table = page.locator('[data-reveal]').filter({ has: page.getByRole('table') })
  const height = await page.locator('.hero-layout').evaluate(element => element.clientHeight)
  await expect(hero).toHaveCSS('opacity', '1')
  await expect(title).toHaveCSS('opacity', '0')
  await page.mouse.wheel(0, 180)
  await expect.poll(() => hero.evaluate(element => Number(getComputedStyle(element).opacity))).toBeLessThan(1)
  await expect(title).toHaveCSS('opacity', '1')
  await page.screenshot({ path: 'test-results/scroll-hero.png' })
  await page.mouse.wheel(0, 420)
  await expect(table).toHaveCSS('opacity', '1')
  await expect(table).toHaveCSS('transform', 'none')
  await page.screenshot({ path: 'test-results/scroll-comparison.png' })
  expect(await page.locator('.hero-layout').evaluate(element => element.clientHeight)).toBe(height)
  await page.mouse.wheel(0, -2000)
  await expect(hero).toHaveCSS('opacity', '1')
  await expect(title).toHaveCSS('opacity', '1')
  await expect(table).toHaveCSS('opacity', '1')
})

test('keyboard navigation reveals the pricing actions immediately', async ({ page }) => {
  await page.goto(base)
  await expect(page.getByRole('switch')).toBeEnabled()
  const table = page.locator('[data-reveal]').filter({ has: page.getByRole('table') })
  await expect(table).toHaveCSS('opacity', '0')
  await page.getByRole('link', { name: 'Compare features', exact: true }).focus()
  // The two social links precede the table's download and account actions.
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Get the free app', exact: true })).toBeFocused()
  await expect(table).toHaveCSS('opacity', '1')
  await expect(table).toHaveCSS('transition-duration', '0s')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Explore Account', exact: true })).toBeFocused()
})

test('changing reduced motion preference reveals content and stops hero movement', async ({ page }) => {
  await page.goto(base)
  await expect(page.getByRole('switch')).toBeEnabled()
  const title = page.getByRole('heading', { name: 'Your finances. Your choice.' })
  await expect(title).toHaveCSS('opacity', '0')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(title).toHaveCSS('opacity', '1')
  await expect(title).toHaveCSS('transition-duration', '0s')
  const hero = page.locator('.hero-copy')
  const restingPosition = await hero.evaluate(element => element.getBoundingClientRect().top + window.scrollY)
  await page.mouse.wheel(0, 180)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
  await expect(hero).toHaveCSS('opacity', '1')
  expect(await hero.evaluate(element => element.getBoundingClientRect().top + window.scrollY)).toBeCloseTo(restingPosition, 1)
  await expect(page.getByRole('heading', { level: 1 })).toHaveCSS('animation-name', 'none')
})

test('content stays visible when intersection observation is unavailable', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'IntersectionObserver', { value: undefined }))
  await page.goto(base)
  await expect(page.getByRole('switch')).toBeEnabled()
  for (const element of await page.locator('[data-reveal]').all()) await expect(element).toHaveCSS('opacity', '1')
})
